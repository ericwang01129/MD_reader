def repl(m):
    inner = m.group(1)
    if inner in M:
        return '>' + M[inner] + '<'
    # if it has Japanese (kana/kanji), record as missing (do not touch attribute placeholders, which are inside quotes not here)
    if re.search(r'[぀-ヿ㐀-鿿々〆〤]', inner):
        missing.append(inner)
    return m.group(0)

